"""Causal coordinate-swap benchmark for ``JacobianLens.coordinate_patch_hooks``.

Tests whether an anchored J-space coordinate edit changes model output, with baseline-capability
filtering, displacement-matched random-atom controls drawn under several seeds, exact
Clopper-Pearson intervals, and a versioned, fingerprinted JSON artifact. The frozen artifact is
generated by ``jacobian_lens_causal_swap_benchmark_cli``.
"""

from __future__ import annotations

import hashlib
import itertools
import json
from collections import Counter
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import (
    Any,
    Container,
    Dict,
    Iterator,
    List,
    Literal,
    Mapping,
    MutableMapping,
    Optional,
    Sequence,
    Tuple,
)

import torch

