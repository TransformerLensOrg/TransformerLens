def build_protocol_manifest(**fields: Any) -> Dict[str, Any]:
    """Returns ``fields`` as a manifest dict, raising if any required manifest field is missing."""
    missing = [name for name in _REQUIRED_MANIFEST_FIELDS if name not in fields]
    if missing:
        raise ValueError(f"protocol manifest is missing required field(s): {', '.join(missing)}")
    return dict(fields)


def fingerprint_manifest(manifest: Dict[str, Any]) -> str:
    """Fingerprints a protocol manifest with the recipe ``Jacobian_Lens_Demo.ipynb`` uses."""
    return hashlib.sha256(
        json.dumps(manifest, sort_keys=True, separators=(",", ":")).encode()
    ).hexdigest()


def results_fingerprint(artifact: Mapping[str, Any]) -> str:
    """Fingerprints the trial, excluded-baseline and CI blocks, which ``protocol_fingerprint``
    does not cover, with the manifest recipe."""
    return hashlib.sha256(
        json.dumps(
            {
                "trials": artifact["trials"],
                "excluded_baselines": artifact["excluded_baselines"],
                "real_success_ci": artifact["real_success_ci"],
                "control_success_ci": artifact["control_success_ci"],
            },
            sort_keys=True,
            separators=(",", ":"),
        ).encode()
    ).hexdigest()


SCHEMA_VERSION = 2


def serialize_artifact(
    manifest: Dict[str, Any],
    trials: Sequence[TrialResult],
    excluded_baselines: Sequence[BaselineRecord],
    real_ci: SuccessRateInterval,
    control_ci: SuccessRateInterval,
) -> Dict[str, Any]:
    """Assembles the JSON-serializable artifact; ``n_independent_prompts`` counts distinct ok
    ``(function, source)`` prompts because trials sharing a prompt are not independent draws."""
    artifact: Dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "protocol_manifest": manifest,
        "protocol_fingerprint": fingerprint_manifest(manifest),
        "trials": [asdict(trial) for trial in trials],
        "excluded_baselines": [asdict(record) for record in excluded_baselines],
        "real_success_ci": asdict(real_ci),
        "control_success_ci": asdict(control_ci),
        "n_independent_prompts": len(
            {(trial.function, trial.source) for trial in trials if trial.status == "ok"}
        ),
        "layers_executed": sorted({trial.layer for trial in trials if trial.status == "ok"}),
        "trial_status_counts": dict(Counter(trial.status for trial in trials)),
    }
    artifact["results_fingerprint"] = results_fingerprint(artifact)
    return artifact


_REQUIRED_ARTIFACT_FIELDS = (
    "schema_version",
    "protocol_manifest",
    "protocol_fingerprint",
    "trials",
    "excluded_baselines",
    "real_success_ci",
    "control_success_ci",
    "n_independent_prompts",
    "layers_executed",
    "trial_status_counts",
    "results_fingerprint",
)


def load_artifact(path: Path) -> Dict[str, Any]:
    """Reads an artifact, raising ``ValueError`` on a missing key, a schema-version mismatch, or
    a stored fingerprint that differs from its recomputation."""
    artifact = json.loads(Path(path).read_text())
    missing = [name for name in _REQUIRED_ARTIFACT_FIELDS if name not in artifact]
    if missing:
        raise ValueError(f"artifact is missing required field(s): {', '.join(missing)}")
    if artifact["schema_version"] != SCHEMA_VERSION:
        raise ValueError(
            f"artifact schema_version {artifact['schema_version']!r} does not match the "
            f"expected {SCHEMA_VERSION!r}"
        )
    expected_fingerprint = fingerprint_manifest(artifact["protocol_manifest"])
    if artifact["protocol_fingerprint"] != expected_fingerprint:
        raise ValueError(
            "artifact protocol_fingerprint does not match a freshly computed fingerprint of "
            "its protocol_manifest (the manifest may have been hand-edited or corrupted)"
        )
    expected_results_fingerprint = results_fingerprint(artifact)
    if artifact["results_fingerprint"] != expected_results_fingerprint:
        raise ValueError(
            "artifact results_fingerprint does not match a freshly computed fingerprint of "
            "its trials, excluded_baselines, and confidence-interval blocks (they may have "
            "been hand-edited or corrupted)"
        )
    return artifact
